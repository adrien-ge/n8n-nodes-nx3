/* Full item record (ITMMASTER): setup columns with local menus resolved. */
SELECT
    ITM.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS DESCRIPTION,
    ISNULL(NULLIF(DES2.LABEL, ''), ITM.ITMDES2_0) AS DESCRIPTION_2,
    ISNULL(NULLIF(DES3.LABEL, ''), ITM.ITMDES3_0) AS DESCRIPTION_3,
    ITM.SEAKEY_0        AS SEARCH_KEY,
    ITM.TCLCOD_0        AS CATEGORY_CODE,
    ISNULL(CAT.LABEL, ITM.TCLCOD_0)   AS CATEGORY_LABEL,
    ITM.ITMSTA_0        AS ITEM_STATUS_CODE,
    ISNULL(ML_STA.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.ITMSTA_0, 0) AS VARCHAR(10)) + ')' AS ITEM_STATUS_LABEL,
    ITM.STDFLG_0        AS MANAGEMENT_MODE_CODE,
    ISNULL(ML_STD.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.STDFLG_0, 0) AS VARCHAR(10)) + ')' AS MANAGEMENT_MODE_LABEL,
    ITM.STOMGTCOD_0     AS STOCK_MANAGEMENT_CODE,
    ISNULL(ML_SMG.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.STOMGTCOD_0, 0) AS VARCHAR(10)) + ')' AS STOCK_MANAGEMENT_LABEL,
    ITM.LOTMGTCOD_0     AS LOT_MANAGEMENT_CODE,
    ISNULL(ML_LOT.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.LOTMGTCOD_0, 0) AS VARCHAR(10)) + ')' AS LOT_MANAGEMENT_LABEL,
    ITM.SERMGTCOD_0     AS SERIAL_MANAGEMENT_CODE,
    ISNULL(ML_SER.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.SERMGTCOD_0, 0) AS VARCHAR(10)) + ')' AS SERIAL_MANAGEMENT_LABEL,
    ITM.TRKCOD_0        AS TRACEABILITY_CODE,
    ISNULL(ML_TRK.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.TRKCOD_0, 0) AS VARCHAR(10)) + ')' AS TRACEABILITY_LABEL,
    ITM.EXYMGTCOD_0     AS EXPIRY_MANAGEMENT_CODE,
    ISNULL(ML_EXY.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.EXYMGTCOD_0, 0) AS VARCHAR(10)) + ')' AS EXPIRY_MANAGEMENT_LABEL,
    ITM.SHL_0           AS SHELF_LIFE,
    ITM.PURFLG_0        AS PURCHASED_CODE,
    ISNULL(ML_PUR.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.PURFLG_0, 0) AS VARCHAR(10)) + ')' AS PURCHASED_LABEL,
    ITM.SALFLG_0        AS SOLD_CODE,
    ISNULL(ML_SAL.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.SALFLG_0, 0) AS VARCHAR(10)) + ')' AS SOLD_LABEL,
    ITM.MFGFLG_0        AS MANUFACTURED_CODE,
    ISNULL(ML_MFG.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.MFGFLG_0, 0) AS VARCHAR(10)) + ')' AS MANUFACTURED_LABEL,
    ITM.DLVFLG_0        AS DELIVERABLE_CODE,
    ISNULL(ML_DLV.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.DLVFLG_0, 0) AS VARCHAR(10)) + ')' AS DELIVERABLE_LABEL,
    ITM.NEGSTO_0        AS NEGATIVE_STOCK_CODE,
    ISNULL(ML_NEG.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.NEGSTO_0, 0) AS VARCHAR(10)) + ')' AS NEGATIVE_STOCK_LABEL,
    ITM.TSICOD_0        AS STAT_GROUP1_CODE,
    ISNULL(AD_TS0.TEXTE_0, 'Not set')  AS STAT_GROUP1_LABEL,
    ITM.TSICOD_1        AS STAT_GROUP2_CODE,
    ISNULL(AD_TS1.TEXTE_0, 'Not set')  AS STAT_GROUP2_LABEL,
    ITM.TSICOD_2        AS STAT_GROUP3_CODE,
    ISNULL(AD_TS2.TEXTE_0, 'Not set')  AS STAT_GROUP3_LABEL,
    ITM.STU_0        AS STOCK_UNIT,
    ITM.SAU_0        AS SALES_UNIT,
    ITM.SAUSTUCOE_0  AS SAL_STK_COEF,
    ITM.PUU_0        AS PURCHASE_UNIT,
    ITM.PUUSTUCOE_0  AS PUR_STK_COEF,
    ITM.WEU_0        AS WEIGHT_UNIT,
    ITM.ITMWEI_0     AS UNIT_WEIGHT,
    ITM.VOU_0        AS VOLUME_UNIT,
    ITM.ITMVOU_0     AS UNIT_VOLUME,
    ITM.EANCOD_0     AS BARCODE,
    ITM.GTIN_0       AS GTIN,
    ITM.CUSREF_0     AS CUSTOMS_CODE,
    ITM.ACCCOD_0     AS ACCOUNTING_CODE,
    ITM.PURBASPRI_0  AS PURCHASE_BASE_PRICE,
    ITM.BUY_0        AS BUYER,
    ITM.PLANNER_0    AS PLANNER,
    ITM.OFS_0        AS REPLENISHMENT_LEAD_TIME,
    ISNULL(STK.STOCK_TOTAL_A, 0)    AS STOCK_TOTAL_A_ALL_SITES,
    ISNULL(STK.STOCK_AVAILABLE, 0) AS STOCK_AVAILABLE_ALL_SITES,
    ISNULL(STK.SITE_COUNT, 0)       AS SITES_WITH_STOCK,
    NULLIF(ITM.CREDAT_0, '1753-01-01') AS CREATED_ON,
    NULLIF(ITM.UPDDAT_0, '1753-01-01') AS UPDATED_ON,
    ITM.UPDUSR_0        AS UPDATED_BY
FROM ITMMASTER ITM
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES2AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES2 ON DES2.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES3AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES3 ON DES3.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN (
    SELECT ITMREF_0,
           SUM(ISNULL(PHYSTO_0, 0)) AS STOCK_TOTAL_A,
           SUM(ISNULL(PHYSTO_0, 0) - ISNULL(PHYALL_0, 0) - ISNULL(GLOALL_0, 0)) AS STOCK_AVAILABLE,
           COUNT(*) AS SITE_COUNT
    FROM   ITMMVT
    GROUP  BY ITMREF_0
) STK ON STK.ITMREF_0 = ITM.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) + RTRIM(IDENT2_0) AS TCLCOD, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMCATEG' AND ZONE_0 = 'TCLAXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0) + RTRIM(IDENT2_0)
) CAT ON CAT.TCLCOD = RTRIM(ITM.TCLCOD_0)
LEFT JOIN APLSTD ML_STA ON ML_STA.LAN_0 = {{lang}} AND ML_STA.LANCHP_0 = 246  AND ML_STA.LANNUM_0 = ITM.ITMSTA_0
LEFT JOIN APLSTD ML_STD ON ML_STD.LAN_0 = {{lang}} AND ML_STD.LANCHP_0 = 297  AND ML_STD.LANNUM_0 = ITM.STDFLG_0
LEFT JOIN APLSTD ML_SMG ON ML_SMG.LAN_0 = {{lang}} AND ML_SMG.LANCHP_0 = 215  AND ML_SMG.LANNUM_0 = ITM.STOMGTCOD_0
LEFT JOIN APLSTD ML_LOT ON ML_LOT.LAN_0 = {{lang}} AND ML_LOT.LANCHP_0 = 2711 AND ML_LOT.LANNUM_0 = ITM.LOTMGTCOD_0
LEFT JOIN APLSTD ML_SER ON ML_SER.LAN_0 = {{lang}} AND ML_SER.LANCHP_0 = 210  AND ML_SER.LANNUM_0 = ITM.SERMGTCOD_0
LEFT JOIN APLSTD ML_TRK ON ML_TRK.LAN_0 = {{lang}} AND ML_TRK.LANCHP_0 = 754  AND ML_TRK.LANNUM_0 = ITM.TRKCOD_0
LEFT JOIN APLSTD ML_EXY ON ML_EXY.LAN_0 = {{lang}} AND ML_EXY.LANCHP_0 = 211  AND ML_EXY.LANNUM_0 = ITM.EXYMGTCOD_0
LEFT JOIN APLSTD ML_PUR ON ML_PUR.LAN_0 = {{lang}} AND ML_PUR.LANCHP_0 = 1    AND ML_PUR.LANNUM_0 = ITM.PURFLG_0
LEFT JOIN APLSTD ML_SAL ON ML_SAL.LAN_0 = {{lang}} AND ML_SAL.LANCHP_0 = 1    AND ML_SAL.LANNUM_0 = ITM.SALFLG_0
LEFT JOIN APLSTD ML_MFG ON ML_MFG.LAN_0 = {{lang}} AND ML_MFG.LANCHP_0 = 1    AND ML_MFG.LANNUM_0 = ITM.MFGFLG_0
LEFT JOIN APLSTD ML_DLV ON ML_DLV.LAN_0 = {{lang}} AND ML_DLV.LANCHP_0 = 1    AND ML_DLV.LANNUM_0 = ITM.DLVFLG_0
LEFT JOIN APLSTD ML_NEG ON ML_NEG.LAN_0 = {{lang}} AND ML_NEG.LANCHP_0 = 1    AND ML_NEG.LANNUM_0 = ITM.NEGSTO_0
LEFT JOIN ATEXTRA AD_TS0 ON AD_TS0.CODFIC_0 = 'ATABDIV' AND AD_TS0.ZONE_0 = 'LNGDES' AND AD_TS0.LANGUE_0 = {{lang}} AND AD_TS0.IDENT1_0 = '20' AND AD_TS0.IDENT2_0 = ITM.TSICOD_0
LEFT JOIN ATEXTRA AD_TS1 ON AD_TS1.CODFIC_0 = 'ATABDIV' AND AD_TS1.ZONE_0 = 'LNGDES' AND AD_TS1.LANGUE_0 = {{lang}} AND AD_TS1.IDENT1_0 = '21' AND AD_TS1.IDENT2_0 = ITM.TSICOD_1
LEFT JOIN ATEXTRA AD_TS2 ON AD_TS2.CODFIC_0 = 'ATABDIV' AND AD_TS2.ZONE_0 = 'LNGDES' AND AD_TS2.LANGUE_0 = {{lang}} AND AD_TS2.IDENT1_0 = '22' AND AD_TS2.IDENT2_0 = ITM.TSICOD_2
WHERE 1 = 1
/*FILTERS*/
ORDER BY ITM.ITMREF_0
