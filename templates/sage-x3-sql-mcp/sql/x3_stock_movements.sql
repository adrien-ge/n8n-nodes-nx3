/* Stock movements, line by line (STOJOU journal). Quantities are signed. */
SELECT
    STJ.STOFCY_0        AS SITE,
    STJ.VCRNUM_0        AS DOCUMENT_NUMBER,
    STJ.VCRLIN_0        AS LINE_NUMBER,
    STJ.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS DESCRIPTION,
    NULLIF(STJ.IPTDAT_0, '1753-01-01')  AS MOVEMENT_DATE,
    NULLIF(STJ.ACCDAT_0, '1753-01-01')  AS ACCOUNTING_DATE,
    NULLIF(STJ.CREDAT_0, '1753-01-01')  AS CREATED_ON,
    STJ.TRSTYP_0        AS MOVEMENT_TYPE_CODE,
    ISNULL(ML_TRS.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(STJ.TRSTYP_0, 0) AS VARCHAR(10)) + ')' AS MOVEMENT_TYPE_LABEL,
    STJ.VCRTYP_0        AS DOCUMENT_TYPE_CODE,
    ISNULL(ML_VCR.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(STJ.VCRTYP_0, 0) AS VARCHAR(10)) + ')' AS DOCUMENT_TYPE_LABEL,
    STJ.VCRTYPORI_0     AS SOURCE_DOCUMENT_TYPE_CODE,
    ISNULL(ML_ORI.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(STJ.VCRTYPORI_0, 0) AS VARCHAR(10)) + ')' AS SOURCE_DOCUMENT_TYPE_LABEL,
    ISNULL(STJ.VCRNUMORI_0, '')         AS SOURCE_DOCUMENT_NUMBER,
    STJ.TRSFAM_0        AS MOVEMENT_FAMILY_CODE,
    ISNULL(AD_FAM.TEXTE_0, 'Not specified') AS MOVEMENT_FAMILY_LABEL,
    CASE WHEN STJ.QTYSTU_0 > 0 THEN 'Inbound' WHEN STJ.QTYSTU_0 < 0 THEN 'Outbound' ELSE 'Neutral' END AS DIRECTION,
    STJ.QTYSTU_0  AS STOCK_QTY,
    STJ.STU_0     AS STOCK_UNIT,
    STJ.QTYPCU_0  AS PACKING_QTY,
    STJ.PCU_0     AS PACKING_UNIT,
    STJ.ACTQTY_0  AS ACTIVE_QTY,
    STJ.POT_0     AS POTENCY,
    STJ.LOT_0     AS LOT,
    STJ.SLO_0     AS SUBLOT,
    STJ.LOC_0     AS LOCATION,
    STJ.WRH_0     AS WAREHOUSE,
    STJ.SERNUM_0  AS SERIAL_NUMBER,
    STJ.STA_0           AS STOCK_STATUS_CODE,
    CASE STJ.STA_0
        WHEN 'A' THEN 'Accepted (A)'
        WHEN 'Q' THEN 'Quality control (Q)'
        WHEN 'R' THEN 'Rejected (R)'
        ELSE ISNULL(NULLIF(STJ.STA_0, ''), 'Not specified')
    END                 AS STOCK_STATUS_LABEL,
    STJ.PRIVAL_0  AS VALUATION_PRICE,
    STJ.AMTVAL_0  AS MOVEMENT_VALUE,
    STJ.PRINAT_0        AS COST_ORIGIN_CODE,
    ISNULL(ML_PRI.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(STJ.PRINAT_0, 0) AS VARCHAR(10)) + ')' AS COST_ORIGIN_LABEL,
    STJ.REGFLG_0        AS ADJUSTED_CODE,
    ISNULL(ML_REG.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(STJ.REGFLG_0, 0) AS VARCHAR(10)) + ')' AS ADJUSTED_LABEL,
    STJ.BPRNUM_0  AS BP_CODE,
    BPR.BPRNAM_0  AS BP_NAME,
    STJ.CREUSR_0  AS USER_CODE,
    STJ.MVTDES_0  AS MOVEMENT_DESCRIPTION
FROM STOJOU STJ
LEFT JOIN ITMMASTER ITM ON ITM.ITMREF_0 = STJ.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN BPARTNER BPR ON BPR.BPRNUM_0 = STJ.BPRNUM_0
LEFT JOIN APLSTD ML_TRS ON ML_TRS.LAN_0 = {{lang}} AND ML_TRS.LANCHP_0 = 704 AND ML_TRS.LANNUM_0 = STJ.TRSTYP_0
LEFT JOIN APLSTD ML_VCR ON ML_VCR.LAN_0 = {{lang}} AND ML_VCR.LANCHP_0 = 701 AND ML_VCR.LANNUM_0 = STJ.VCRTYP_0
LEFT JOIN APLSTD ML_ORI ON ML_ORI.LAN_0 = {{lang}} AND ML_ORI.LANCHP_0 = 701 AND ML_ORI.LANNUM_0 = STJ.VCRTYPORI_0
LEFT JOIN APLSTD ML_PRI ON ML_PRI.LAN_0 = {{lang}} AND ML_PRI.LANCHP_0 = 705 AND ML_PRI.LANNUM_0 = STJ.PRINAT_0
LEFT JOIN APLSTD ML_REG ON ML_REG.LAN_0 = {{lang}} AND ML_REG.LANCHP_0 = 1   AND ML_REG.LANNUM_0 = STJ.REGFLG_0
LEFT JOIN ATEXTRA AD_FAM ON AD_FAM.CODFIC_0 = 'ATABDIV' AND AD_FAM.ZONE_0 = 'LNGDES' AND AD_FAM.LANGUE_0 = {{lang}} AND AD_FAM.IDENT1_0 = '9' AND AD_FAM.IDENT2_0 = STJ.TRSFAM_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY STJ.IPTDAT_0 DESC, STJ.VCRNUM_0, STJ.VCRLIN_0
