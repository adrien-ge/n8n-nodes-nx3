/* Stock detail by lot, sublot, location and status (STOCK). */
SELECT
    STO.STOFCY_0        AS SITE,
    STO.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS DESCRIPTION,
    STO.LOT_0           AS LOT,
    STO.SLO_0           AS SUBLOT,
    STO.BPSLOT_0        AS SUPPLIER_LOT,
    STO.SERNUM_0        AS SERIAL_NUMBER,
    STO.LOC_0           AS LOCATION,
    STO.LOCTYP_0        AS LOCATION_TYPE,
    STO.WRH_0           AS WAREHOUSE,
    STO.PALNUM_0        AS CONTAINER,
    STO.OWNER_0         AS OWNER,
    STO.STA_0           AS STOCK_STATUS_CODE,
    CASE STO.STA_0
        WHEN 'A' THEN 'Accepted (A)'
        WHEN 'Q' THEN 'Quality control (Q)'
        WHEN 'R' THEN 'Rejected (R)'
        ELSE ISNULL(NULLIF(STO.STA_0, ''), 'Not specified')
    END                 AS STOCK_STATUS_LABEL,
    STO.QTYSTU_0     AS STOCK_QTY,
    ITM.STU_0        AS STOCK_UNIT,
    STO.QTYSTUACT_0  AS ACTIVE_QTY,
    STO.QTYPCU_0     AS PACKING_QTY,
    STO.PCU_0        AS PACKING_UNIT,
    ISNULL(STO.CUMALLQTY_0, 0)  AS ALLOCATED_QTY,
    ISNULL(STO.CUMWIPQTY_0, 0)  AS WIP_QTY,
    STO.QTYSTU_0 - ISNULL(STO.CUMALLQTY_0, 0) AS AVAILABLE_QTY,
    NULLIF(STO.LASRCPDAT_0, '1753-01-01') AS LAST_RECEIPT,
    NULLIF(STO.LASISSDAT_0, '1753-01-01') AS LAST_ISSUE,
    NULLIF(STO.LASCUNDAT_0, '1753-01-01') AS LAST_COUNT,
    STO.CUNLOKFLG_0     AS COUNT_IN_PROGRESS_CODE,
    ISNULL(ML_CUN.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(STO.CUNLOKFLG_0, 0) AS VARCHAR(10)) + ')' AS COUNT_IN_PROGRESS_LABEL
FROM STOCK STO
LEFT JOIN ITMMASTER ITM ON ITM.ITMREF_0 = STO.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN APLSTD ML_CUN ON ML_CUN.LAN_0 = {{lang}} AND ML_CUN.LANCHP_0 = 1 AND ML_CUN.LANNUM_0 = STO.CUNLOKFLG_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY STO.ITMREF_0, STO.STOFCY_0, STO.STA_0, STO.LOT_0, STO.LOC_0
