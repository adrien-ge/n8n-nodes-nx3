/* Sales order lines (SORDER + SORDERP + SORDERQ): ordered quantities, the history. */
SELECT
    SOH.SOHNUM_0  AS ORDER_NUMBER,
    SOH.SOHTYP_0  AS ORDER_TYPE,
    SOH.BPCORD_0  AS CUSTOMER_CODE,
    BPC.BPCNAM_0  AS CUSTOMER_NAME,
    SOH.SALFCY_0  AS SALES_SITE,
    NULLIF(SOH.ORDDAT_0, '1753-01-01') AS ORDER_DATE,
    SOH.CUR_0     AS CURRENCY,
    SOH.ORDSTA_0  AS STATUS_CODE,
    ISNULL(ML_ORD.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(SOH.ORDSTA_0, 0) AS VARCHAR(10)) + ')' AS STATUS_LABEL,
    SOP.SOPLIN_0    AS LINE_NUMBER,
    SOP.ITMREF_0    AS ITEM,
    SOP.ITMDES1_0   AS DESCRIPTION,
    SOP.ITMREFBPC_0 AS CUSTOMER_REF,
    SOQ.QTY         AS ORDERED_QTY,
    SOP.NETPRI_0    AS NET_PRICE,
    SOQ.QTY * SOP.NETPRI_0 AS LINE_AMOUNT_EXCL_TAX
FROM SORDER SOH
JOIN SORDERP SOP ON SOP.SOHNUM_0 = SOH.SOHNUM_0
LEFT JOIN (
    SELECT SOHNUM_0, SOPLIN_0, SUM(QTY_0) AS QTY
    FROM SORDERQ
    GROUP BY SOHNUM_0, SOPLIN_0
) SOQ ON SOQ.SOHNUM_0 = SOP.SOHNUM_0 AND SOQ.SOPLIN_0 = SOP.SOPLIN_0
LEFT JOIN BPCUSTOMER BPC ON BPC.BPCNUM_0 = SOH.BPCORD_0
LEFT JOIN APLSTD ML_ORD ON ML_ORD.LAN_0 = {{lang}} AND ML_ORD.LANCHP_0 = 415 AND ML_ORD.LANNUM_0 = SOH.ORDSTA_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY SOH.ORDDAT_0 DESC, SOH.SOHNUM_0, SOP.SOPLIN_0
