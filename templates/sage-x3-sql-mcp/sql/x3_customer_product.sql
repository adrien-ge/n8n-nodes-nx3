/* Item x customer cross-reference (ITMBPC): the customer's own item reference. */
SELECT
    ITU.BPCNUM_0  AS CUSTOMER_CODE,
    BPC.BPCNAM_0  AS CUSTOMER_NAME,
    BPC.BCGCOD_0  AS CUSTOMER_CATEGORY,
    BPC.BPCSTA_0        AS CUSTOMER_STATUS_CODE,
    ISNULL(ML_BPC.LANMES_0, 'Unknown')
        + ' (' + CAST(ISNULL(BPC.BPCSTA_0, 0) AS VARCHAR(10)) + ')' AS CUSTOMER_STATUS_LABEL,
    ITU.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS X3_DESCRIPTION,
    ITU.ITMREFBPC_0     AS CUSTOMER_REF,
    ITU.ITMDESBPC_0     AS CUSTOMER_DESCRIPTION,
    ITU.ENAFLG_0        AS ACTIVE_CODE,
    ISNULL(ML_ENA.LANMES_0, 'Unknown')
        + ' (' + CAST(ISNULL(ITU.ENAFLG_0, 0) AS VARCHAR(10)) + ')' AS ACTIVE_LABEL,
    ITM.ITMSTA_0        AS ITEM_STATUS_CODE,
    ISNULL(ML_ITM.LANMES_0, 'Unknown')
        + ' (' + CAST(ISNULL(ITM.ITMSTA_0, 0) AS VARCHAR(10)) + ')' AS ITEM_STATUS_LABEL,
    ITM.TCLCOD_0        AS ITEM_CATEGORY_CODE,
    ISNULL(CAT.LABEL, ITM.TCLCOD_0)   AS ITEM_CATEGORY_LABEL,
    ITU.SAU_0         AS CUSTOMER_SALES_UNIT,
    ITU.SAUSTUCOE_0   AS SAL_STK_COEF,
    ITM.STU_0         AS STOCK_UNIT,
    ITU.PCK_0         AS PACKING,
    ITU.PCKCAP_0      AS PACKING_CAPACITY,
    ITU.PCU1_0        AS PACK_UNIT_1,
    ITU.PCUSAUCOE1_0  AS PACK_COEF_1,
    ITU.PCU2_0        AS PACK_UNIT_2,
    ITU.PCUSAUCOE2_0  AS PACK_COEF_2,
    ITU.DLUBPC_0      AS CUSTOMER_SHELF_LIFE_COEF,
    ISNULL(STK.STOCK_AVAILABLE, 0) AS STOCK_AVAILABLE_ALL_SITES,
    NULLIF(ITU.CREDAT_0, '1753-01-01') AS CREATED_ON,
    NULLIF(ITU.UPDDAT_0, '1753-01-01') AS UPDATED_ON,
    ITU.UPDUSR_0        AS UPDATED_BY
FROM ITMBPC ITU
LEFT JOIN BPCUSTOMER BPC ON BPC.BPCNUM_0 = ITU.BPCNUM_0
LEFT JOIN ITMMASTER ITM ON ITM.ITMREF_0 = ITU.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA
    WHERE  CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN (
    SELECT ITMREF_0,
           SUM(ISNULL(PHYSTO_0, 0) - ISNULL(PHYALL_0, 0) - ISNULL(GLOALL_0, 0)) AS STOCK_AVAILABLE
    FROM   ITMMVT
    GROUP  BY ITMREF_0
) STK ON STK.ITMREF_0 = ITU.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) + RTRIM(IDENT2_0) AS TCLCOD, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA
    WHERE  CODFIC_0 = 'ITMCATEG' AND ZONE_0 = 'TCLAXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0) + RTRIM(IDENT2_0)
) CAT ON CAT.TCLCOD = RTRIM(ITM.TCLCOD_0)
LEFT JOIN APLSTD ML_ENA ON ML_ENA.LAN_0 = {{lang}} AND ML_ENA.LANCHP_0 = 1   AND ML_ENA.LANNUM_0 = ITU.ENAFLG_0
LEFT JOIN APLSTD ML_BPC ON ML_BPC.LAN_0 = {{lang}} AND ML_BPC.LANCHP_0 = 1   AND ML_BPC.LANNUM_0 = BPC.BPCSTA_0
LEFT JOIN APLSTD ML_ITM ON ML_ITM.LAN_0 = {{lang}} AND ML_ITM.LANCHP_0 = 246 AND ML_ITM.LANNUM_0 = ITM.ITMSTA_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY ITU.BPCNUM_0, ITU.ITMREF_0
