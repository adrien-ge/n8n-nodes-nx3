/* Downstream impact of a purchased component: open work orders consuming it (MFGMAT + MFGHEAD),
   the finished item they produce (MFGITM) and the open sales order lines pulling that finished item. */
SELECT
    MFM.ITMREF_0                        AS COMPONENT,
    MFM.MFGNUM_0                        AS WORK_ORDER,
    MFG.MFGSTA_0                        AS WO_STATUS_CODE,
    ISNULL(ML_MST.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(MFG.MFGSTA_0, 0) AS VARCHAR(10)) + ')' AS WO_STATUS_LABEL,
    MFM.MFGFCY_0                        AS WO_SITE,
    NULLIF(MFM.RETDAT_0, '1753-01-01')  AS COMPONENT_NEED_DATE,
    NULLIF(MFG.STRDAT_0, '1753-01-01')  AS WO_START_DATE,
    NULLIF(MFG.ENDDAT_0, '1753-01-01')  AS WO_END_DATE,
    MFM.RETQTY_0 - MFM.USEQTY_0         AS COMPONENT_QTY_STILL_NEEDED,
    ITVC.STOFCY_0                       AS COMPONENT_STOCK_SITE,
    ISNULL(ITVC.PHYSTO_0, 0) - ISNULL(ITVC.PHYALL_0, 0) - ISNULL(ITVC.GLOALL_0, 0) AS COMPONENT_STOCK_AVAILABLE,
    MFI.ITMREF_0                        AS FINISHED_ITEM,
    MFI.EXTQTY_0                        AS WO_PLANNED_QTY,
    MFI.RMNEXTQTY_0                     AS WO_REMAINING_QTY,
    ITVP.STOFCY_0                       AS FINISHED_STOCK_SITE,
    ISNULL(ITVP.PHYSTO_0, 0) - ISNULL(ITVP.PHYALL_0, 0) - ISNULL(ITVP.GLOALL_0, 0) AS FINISHED_STOCK_AVAILABLE,
    SOQ.SOHNUM_0                        AS SALES_ORDER,
    SOQ.SOQSTA_0                        AS SO_LINE_STATUS_CODE,
    ISNULL(ML_SST.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(SOQ.SOQSTA_0, 0) AS VARCHAR(10)) + ')' AS SO_LINE_STATUS_LABEL,
    SOH.BPCORD_0                        AS CUSTOMER_CODE,
    SOH.BPCNAM_0                        AS CUSTOMER_NAME,
    SOH.CREUSR_0                        AS SO_CREATED_BY,
    ISNULL(AUS.NOMUSR_0, '')            AS SO_CREATED_BY_NAME,
    ISNULL(AUS.ADDEML_0, '')            AS SO_CREATED_BY_EMAIL,
    SOQ.QTY_0                           AS SO_ORDERED_QTY,
    SOQ.DLVQTY_0                        AS SO_DELIVERED_QTY,
    SOQ.QTY_0 - SOQ.DLVQTY_0            AS SO_QTY_TO_DELIVER,
    NULLIF(SOQ.DEMDLVDAT_0, '1753-01-01') AS SO_REQUESTED_DELIVERY_DATE
FROM MFGMAT MFM
INNER JOIN MFGHEAD MFG ON MFG.MFGNUM_0 = MFM.MFGNUM_0
INNER JOIN MFGITM  MFI ON MFI.MFGNUM_0 = MFM.MFGNUM_0
LEFT JOIN ITMMVT ITVC ON ITVC.ITMREF_0 = MFM.ITMREF_0 AND ITVC.STOFCY_0 = MFM.MFGFCY_0
LEFT JOIN ITMMVT ITVP ON ITVP.ITMREF_0 = MFI.ITMREF_0 AND ITVP.STOFCY_0 = MFI.MFGFCY_0
LEFT JOIN SORDERQ SOQ ON SOQ.ITMREF_0 = MFI.ITMREF_0 AND SOQ.SOQSTA_0 = 1
LEFT JOIN SORDER  SOH ON SOH.SOHNUM_0 = SOQ.SOHNUM_0
LEFT JOIN AUTILIS AUS ON AUS.USR_0 = SOH.CREUSR_0
LEFT JOIN ATABZON ATZM ON ATZM.CODFIC_0 = 'MFGHEAD' AND ATZM.CODZONE_0 = 'MFGSTA'
LEFT JOIN APLSTD ML_MST ON ML_MST.LAN_0 = {{lang}} AND ML_MST.LANCHP_0 = ATZM.NOLIB_0 AND ML_MST.LANNUM_0 = MFG.MFGSTA_0
LEFT JOIN ATABZON ATZS ON ATZS.CODFIC_0 = 'SORDERQ' AND ATZS.CODZONE_0 = 'SOQSTA'
LEFT JOIN APLSTD ML_SST ON ML_SST.LAN_0 = {{lang}} AND ML_SST.LANCHP_0 = ATZS.NOLIB_0 AND ML_SST.LANNUM_0 = SOQ.SOQSTA_0
WHERE MFG.MFGSTA_0 IN (1, 2)
  AND (MFM.RETQTY_0 - MFM.USEQTY_0) > 0
/*FILTERS*/
ORDER BY MFM.ITMREF_0, MFM.MFGNUM_0, MFI.ITMREF_0
