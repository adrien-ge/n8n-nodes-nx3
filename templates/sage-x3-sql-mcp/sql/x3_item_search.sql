/* Item search (ITMMASTER), deliberately short: 10 columns. */
SELECT
    ITM.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS DESCRIPTION,
    ITM.SEAKEY_0        AS SEARCH_KEY,
    ITM.TCLCOD_0        AS CATEGORY_CODE,
    ISNULL(CAT.LABEL, ITM.TCLCOD_0)   AS CATEGORY_LABEL,
    ITM.ITMSTA_0        AS ITEM_STATUS_CODE,
    ISNULL(ML_STA.LANMES_0, 'Unknown')
        + ' (' + CAST(ISNULL(ITM.ITMSTA_0, 0) AS VARCHAR(10)) + ')' AS ITEM_STATUS_LABEL,
    ITM.STU_0           AS STOCK_UNIT,
    ISNULL(STK.STOCK_TOTAL_A, 0)    AS STOCK_TOTAL_ALL_SITES,
    ISNULL(STK.STOCK_AVAILABLE, 0) AS STOCK_AVAILABLE_ALL_SITES
FROM ITMMASTER ITM
LEFT JOIN (
    SELECT ITMREF_0,
           SUM(ISNULL(PHYSTO_0, 0)) AS STOCK_TOTAL_A,
           SUM(ISNULL(PHYSTO_0, 0) - ISNULL(PHYALL_0, 0) - ISNULL(GLOALL_0, 0)) AS STOCK_AVAILABLE
    FROM   ITMMVT
    GROUP  BY ITMREF_0
) STK ON STK.ITMREF_0 = ITM.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) + RTRIM(IDENT2_0) AS TCLCOD, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA
    WHERE  CODFIC_0 = 'ITMCATEG' AND ZONE_0 = 'TCLAXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0) + RTRIM(IDENT2_0)
) CAT ON CAT.TCLCOD = RTRIM(ITM.TCLCOD_0)
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA
    WHERE  CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN APLSTD ML_STA ON ML_STA.LAN_0 = {{lang}} AND ML_STA.LANCHP_0 = 246 AND ML_STA.LANNUM_0 = ITM.ITMSTA_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY ITM.ITMREF_0
