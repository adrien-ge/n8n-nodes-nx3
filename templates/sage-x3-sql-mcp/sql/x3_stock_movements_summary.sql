/* Stock movement totals by site, item and movement type over a period (STOJOU). */
SELECT
    STJ.STOFCY_0        AS SITE,
    STJ.ITMREF_0        AS ITEM,
    MAX(ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0)) AS DESCRIPTION,
    STJ.TRSTYP_0        AS MOVEMENT_TYPE_CODE,
    MAX(ISNULL(ML_TRS.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(STJ.TRSTYP_0, 0) AS VARCHAR(10)) + ')') AS MOVEMENT_TYPE_LABEL,
    MAX(ITM.STU_0)      AS STOCK_UNIT,
    COUNT(*)            AS MOVEMENT_COUNT,
    SUM(CASE WHEN STJ.QTYSTU_0 > 0 THEN STJ.QTYSTU_0 ELSE 0 END) AS INBOUND_QTY,
    SUM(CASE WHEN STJ.QTYSTU_0 < 0 THEN STJ.QTYSTU_0 ELSE 0 END) AS OUTBOUND_QTY,
    SUM(STJ.QTYSTU_0)                        AS NET_QTY,
    SUM(ISNULL(STJ.AMTVAL_0, 0))             AS TOTAL_VALUE,
    MIN(NULLIF(STJ.IPTDAT_0, '1753-01-01'))  AS FIRST_MOVEMENT,
    MAX(NULLIF(STJ.IPTDAT_0, '1753-01-01'))  AS LAST_MOVEMENT
FROM STOJOU STJ
LEFT JOIN ITMMASTER ITM ON ITM.ITMREF_0 = STJ.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN APLSTD ML_TRS ON ML_TRS.LAN_0 = {{lang}} AND ML_TRS.LANCHP_0 = 704 AND ML_TRS.LANNUM_0 = STJ.TRSTYP_0
WHERE 1 = 1
/*FILTERS*/
GROUP BY STJ.STOFCY_0, STJ.ITMREF_0, STJ.TRSTYP_0
ORDER BY STJ.STOFCY_0, STJ.ITMREF_0, STJ.TRSTYP_0
