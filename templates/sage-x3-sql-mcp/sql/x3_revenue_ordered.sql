/* Order book: ordered and not yet invoiced, line by line (SORDERQ + SORDERP + SORDER). */
SELECT
    'Ordered'     AS REVENUE_TYPE,
    SOQ.SOHNUM_0  AS DOCUMENT,
    SOQ.SOPLIN_0  AS LINE,
    NULLIF(SOQ.SHIDAT_0, '1753-01-01') AS REF_DATE,
    YEAR(SOQ.SHIDAT_0)  AS YEAR,
    MONTH(SOQ.SHIDAT_0) AS MONTH,
    SOQ.BPCORD_0  AS CUSTOMER_CODE,
    BPC.BPCNAM_0  AS CUSTOMER_NAME,
    SOP.REP1_0    AS SALES_REP,
    SOQ.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS DESCRIPTION,
    ITM.TCLCOD_0        AS X3_CATEGORY,
    ISNULL(CAT.LABEL, ITM.TCLCOD_0) AS X3_CATEGORY_LABEL,
    ISNULL(AD_TS0.TEXTE_0, 'Not set') AS STAT_GROUP1,
    SOQ.STOFCY_0        AS SITE,
    (SOQ.QTY_0 - ISNULL(SOQ.INVQTY_0, 0)) AS QUANTITY,
    SOP.STU_0           AS UNIT,
    SOH.CUR_0           AS CURRENCY,
    (SOQ.QTY_0 - ISNULL(SOQ.INVQTY_0, 0)) * SOP.NETPRI_0 AS AMOUNT_CURRENCY,
    CASE WHEN SOH.CUR_0 = 'EUR' THEN 1 ELSE COALESCE(
        (SELECT TOP (1) TCH.CHGRAT_0
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = SOH.CUR_0 AND TCH.CURDEN_0 = 'EUR' AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SOH.ORDDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC),
        (SELECT TOP (1) 1.0 / NULLIF(TCH.CHGRAT_0, 0)
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = 'EUR' AND TCH.CURDEN_0 = SOH.CUR_0 AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SOH.ORDDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC)
    ) END           AS EUR_RATE,
    (SOQ.QTY_0 - ISNULL(SOQ.INVQTY_0, 0)) * SOP.NETPRI_0
    * CASE WHEN SOH.CUR_0 = 'EUR' THEN 1 ELSE COALESCE(
        (SELECT TOP (1) TCH.CHGRAT_0
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = SOH.CUR_0 AND TCH.CURDEN_0 = 'EUR' AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SOH.ORDDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC),
        (SELECT TOP (1) 1.0 / NULLIF(TCH.CHGRAT_0, 0)
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = 'EUR' AND TCH.CURDEN_0 = SOH.CUR_0 AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SOH.ORDDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC)
    ) END           AS AMOUNT_EUR,
    SOQ.SOQSTA_0        AS STATUS_CODE,
    ISNULL(ML_SOQ.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(SOQ.SOQSTA_0, 0) AS VARCHAR(10)) + ')' AS STATUS_LABEL,
    SOH.ORDSTA_0        AS ORDER_STATUS_CODE,
    ISNULL(ML_ORD.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(SOH.ORDSTA_0, 0) AS VARCHAR(10)) + ')' AS ORDER_STATUS_LABEL,
    SOQ.SOHCAT_0        AS ORDER_CATEGORY_CODE,
    ISNULL(ML_CAT.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(SOQ.SOHCAT_0, 0) AS VARCHAR(10)) + ')' AS ORDER_CATEGORY_LABEL,
    SOQ.INVFLG_0        AS INVOICED_CODE,
    ISNULL(ML_INV.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(SOQ.INVFLG_0, 0) AS VARCHAR(10)) + ')' AS INVOICED_LABEL,
    SOQ.QTY_0     AS ORDERED_QTY,
    SOQ.DLVQTY_0  AS DELIVERED_QTY,
    SOQ.INVQTY_0  AS INVOICED_QTY,
    SOQ.ALLQTY_0  AS ALLOCATED_QTY,
    SOQ.SHTQTY_0  AS SHORTAGE_QTY,
    SOP.NETPRI_0  AS NET_PRICE
FROM SORDERQ SOQ
JOIN SORDERP SOP ON SOP.SOHNUM_0 = SOQ.SOHNUM_0 AND SOP.SOPLIN_0 = SOQ.SOPLIN_0
LEFT JOIN SORDER SOH     ON SOH.SOHNUM_0 = SOQ.SOHNUM_0
LEFT JOIN BPCUSTOMER BPC ON BPC.BPCNUM_0 = SOQ.BPCORD_0
LEFT JOIN ITMMASTER  ITM ON ITM.ITMREF_0 = SOQ.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) + RTRIM(IDENT2_0) AS TCLCOD, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMCATEG' AND ZONE_0 = 'TCLAXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0) + RTRIM(IDENT2_0)
) CAT ON CAT.TCLCOD = RTRIM(ITM.TCLCOD_0)
LEFT JOIN ATEXTRA AD_TS0 ON AD_TS0.CODFIC_0 = 'ATABDIV' AND AD_TS0.ZONE_0 = 'LNGDES' AND AD_TS0.LANGUE_0 = {{lang}} AND AD_TS0.IDENT1_0 = '20' AND AD_TS0.IDENT2_0 = ITM.TSICOD_0
LEFT JOIN APLSTD ML_SOQ ON ML_SOQ.LAN_0 = {{lang}} AND ML_SOQ.LANCHP_0 = 279 AND ML_SOQ.LANNUM_0 = SOQ.SOQSTA_0
LEFT JOIN APLSTD ML_ORD ON ML_ORD.LAN_0 = {{lang}} AND ML_ORD.LANCHP_0 = 415 AND ML_ORD.LANNUM_0 = SOH.ORDSTA_0
LEFT JOIN APLSTD ML_CAT ON ML_CAT.LAN_0 = {{lang}} AND ML_CAT.LANCHP_0 = 412 AND ML_CAT.LANNUM_0 = SOQ.SOHCAT_0
LEFT JOIN APLSTD ML_INV ON ML_INV.LAN_0 = {{lang}} AND ML_INV.LANCHP_0 = 1   AND ML_INV.LANNUM_0 = SOQ.INVFLG_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY SOQ.SHIDAT_0, SOQ.SOHNUM_0, SOQ.SOPLIN_0
