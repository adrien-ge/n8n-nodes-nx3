/* Billed revenue line by line (SINVOICED + SINVOICE), business sign from TABSIVTYP.INVTYP_0. */
SELECT
    'Billed'      AS REVENUE_TYPE,
    SID.NUM_0     AS DOCUMENT,
    SID.SIDLIN_0  AS LINE,
    NULLIF(SIE.ACCDAT_0, '1753-01-01') AS REF_DATE,
    YEAR(SIE.ACCDAT_0)  AS YEAR,
    MONTH(SIE.ACCDAT_0) AS MONTH,
    SID.BPCINV_0  AS CUSTOMER_CODE,
    BPR.BPRNAM_0  AS CUSTOMER_NAME,
    SID.REP1_0    AS SALES_REP,
    SID.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS DESCRIPTION,
    ITM.TCLCOD_0        AS X3_CATEGORY,
    ISNULL(CAT.LABEL, ITM.TCLCOD_0) AS X3_CATEGORY_LABEL,
    ISNULL(AD_TS0.TEXTE_0, 'Not set') AS STAT_GROUP1,
    SID.SALFCY_0  AS SITE,
    SID.STOFCY_0  AS SHIPMENT_SITE,
    (CASE ISNULL(TIV.INVTYP_0, 1) WHEN 2 THEN -1 WHEN 4 THEN -1 WHEN 5 THEN 0 ELSE 1 END) * SID.QTY_0 AS QUANTITY,
    SID.STU_0           AS UNIT,
    SIE.CUR_0           AS CURRENCY,
    (CASE ISNULL(TIV.INVTYP_0, 1) WHEN 2 THEN -1 WHEN 4 THEN -1 WHEN 5 THEN 0 ELSE 1 END) * SID.AMTNOTLIN_0 AS AMOUNT_CURRENCY,
    CASE WHEN SIE.CUR_0 = 'EUR' THEN 1 ELSE COALESCE(
        (SELECT TOP (1) TCH.CHGRAT_0
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = SIE.CUR_0 AND TCH.CURDEN_0 = 'EUR' AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SIE.ACCDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC),
        (SELECT TOP (1) 1.0 / NULLIF(TCH.CHGRAT_0, 0)
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = 'EUR' AND TCH.CURDEN_0 = SIE.CUR_0 AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SIE.ACCDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC)
    ) END           AS EUR_RATE,
    (CASE ISNULL(TIV.INVTYP_0, 1) WHEN 2 THEN -1 WHEN 4 THEN -1 WHEN 5 THEN 0 ELSE 1 END) * SID.AMTNOTLIN_0
    * CASE WHEN SIE.CUR_0 = 'EUR' THEN 1 ELSE COALESCE(
        (SELECT TOP (1) TCH.CHGRAT_0
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = SIE.CUR_0 AND TCH.CURDEN_0 = 'EUR' AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SIE.ACCDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC),
        (SELECT TOP (1) 1.0 / NULLIF(TCH.CHGRAT_0, 0)
           FROM TABCHANGE TCH
          WHERE TCH.CUR_0 = 'EUR' AND TCH.CURDEN_0 = SIE.CUR_0 AND TCH.CHGTYP_0 = 1
            AND TCH.CHGSTRDAT_0 <= SIE.ACCDAT_0
          ORDER BY TCH.CHGSTRDAT_0 DESC)
    ) END           AS AMOUNT_EUR,
    SIE.SIVTYP_0        AS STATUS_CODE,
    CASE ISNULL(TIV.INVTYP_0, 0)
        WHEN 1 THEN 'Invoice (1)'
        WHEN 2 THEN 'Credit memo (2)'
        WHEN 3 THEN 'Debit note (3)'
        WHEN 4 THEN 'Credit note (4)'
        WHEN 5 THEN 'Proforma (5)'
        ELSE 'Not specified (' + RTRIM(ISNULL(SIE.SIVTYP_0, '')) + ')'
    END                 AS STATUS_LABEL
FROM SINVOICED SID
JOIN SINVOICE  SIE ON SIE.NUM_0 = SID.NUM_0
LEFT JOIN TABSIVTYP TIV ON TIV.SIVTYP_0 = SIE.SIVTYP_0
LEFT JOIN ITMMASTER ITM ON ITM.ITMREF_0 = SID.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) + RTRIM(IDENT2_0) AS TCLCOD, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMCATEG' AND ZONE_0 = 'TCLAXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0) + RTRIM(IDENT2_0)
) CAT ON CAT.TCLCOD = RTRIM(ITM.TCLCOD_0)
LEFT JOIN BPARTNER BPR ON BPR.BPRNUM_0 = SID.BPCINV_0
LEFT JOIN ATEXTRA AD_TS0 ON AD_TS0.CODFIC_0 = 'ATABDIV' AND AD_TS0.ZONE_0 = 'LNGDES' AND AD_TS0.LANGUE_0 = {{lang}} AND AD_TS0.IDENT1_0 = '20' AND AD_TS0.IDENT2_0 = ITM.TSICOD_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY SIE.ACCDAT_0 DESC, SID.NUM_0, SID.SIDLIN_0
