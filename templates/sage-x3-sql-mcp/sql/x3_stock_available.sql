/* Available stock by item and site (ITMMVT totals + ITMFACILIT replenishment parameters). */
SELECT
    ITV.STOFCY_0        AS SITE,
    ITV.ITMREF_0        AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS DESCRIPTION,
    ITM.STU_0           AS STOCK_UNIT,
    ITM.TCLCOD_0        AS CATEGORY_CODE,
    ISNULL(CAT.LABEL, ITM.TCLCOD_0)   AS CATEGORY_LABEL,
    ITM.ITMSTA_0        AS ITEM_STATUS_CODE,
    ISNULL(ML_STA.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.ITMSTA_0, 0) AS VARCHAR(10)) + ')' AS ITEM_STATUS_LABEL,
    ITM.STOMGTCOD_0     AS STOCK_MANAGEMENT_CODE,
    ISNULL(ML_SMG.LANMES_0, 'Unknown') + ' (' + CAST(ISNULL(ITM.STOMGTCOD_0, 0) AS VARCHAR(10)) + ')' AS STOCK_MANAGEMENT_LABEL,
    ISNULL(ITV.PHYSTO_0, 0)  AS STOCK_ACCEPTED_A,
    ISNULL(ITV.CTLSTO_0, 0)  AS STOCK_QUALITY_Q,
    ISNULL(ITV.REJSTO_0, 0)  AS STOCK_REJECTED_R,
    ISNULL(ITV.PHYSTO_0, 0) + ISNULL(ITV.CTLSTO_0, 0) + ISNULL(ITV.REJSTO_0, 0) AS STOCK_TOTAL,
    ISNULL(ITV.PHYALL_0, 0)  AS ALLOCATED_DETAILED,
    ISNULL(ITV.GLOALL_0, 0)  AS ALLOCATED_GLOBAL,
    ISNULL(ITV.GLOSHT_0, 0)  AS SHORTAGE_GLOBAL,
    ISNULL(ITV.SALSTO_0, 0)  AS EXPECTED_SALES_ORDERS,
    ISNULL(ITV.ORDSTO_0, 0)  AS EXPECTED_REPLENISHMENT,
    ISNULL(ITV.TRFSTO_0, 0)  AS IN_TRANSIT,
    ISNULL(ITV.WAISTO_0, 0)  AS PENDING_ISSUES,
    ISNULL(ITV.PHYSTO_0, 0) - ISNULL(ITV.PHYALL_0, 0) - ISNULL(ITV.GLOALL_0, 0) AS STOCK_AVAILABLE,
    ISNULL(ITF.REOTSD_0, 0)  AS REORDER_POINT,
    ISNULL(ITF.SAFSTO_0, 0)  AS SAFETY_STOCK,
    ISNULL(ITF.MAXSTO_0, 0)  AS STOCK_MAX,
    CASE
        WHEN ISNULL(ITF.REOTSD_0, 0) > 0
         AND (ISNULL(ITV.PHYSTO_0, 0) - ISNULL(ITV.PHYALL_0, 0) - ISNULL(ITV.GLOALL_0, 0)) < ITF.REOTSD_0
        THEN 'Yes' ELSE 'No'
    END                      AS BELOW_REORDER_POINT,
    ITV.AVC_0                AS AVERAGE_COST,
    ISNULL(ITV.PHYSTO_0, 0) * ISNULL(ITV.AVC_0, 0) AS STOCK_VALUE_A,
    NULLIF(ITV.LASRCPDAT_0, '1753-01-01') AS LAST_RECEIPT,
    NULLIF(ITV.LASISSDAT_0, '1753-01-01') AS LAST_ISSUE,
    NULLIF(ITV.LASCUNDAT_0, '1753-01-01') AS LAST_COUNT
FROM ITMMVT ITV
LEFT JOIN ITMMASTER ITM ON ITM.ITMREF_0 = ITV.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
LEFT JOIN ITMFACILIT ITF ON ITF.ITMREF_0 = ITV.ITMREF_0 AND ITF.STOFCY_0 = ITV.STOFCY_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) + RTRIM(IDENT2_0) AS TCLCOD, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMCATEG' AND ZONE_0 = 'TCLAXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0) + RTRIM(IDENT2_0)
) CAT ON CAT.TCLCOD = RTRIM(ITM.TCLCOD_0)
LEFT JOIN APLSTD ML_STA ON ML_STA.LAN_0 = {{lang}} AND ML_STA.LANCHP_0 = 246 AND ML_STA.LANNUM_0 = ITM.ITMSTA_0
LEFT JOIN APLSTD ML_SMG ON ML_SMG.LAN_0 = {{lang}} AND ML_SMG.LANCHP_0 = 215 AND ML_SMG.LANNUM_0 = ITM.STOMGTCOD_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY ITV.ITMREF_0, ITV.STOFCY_0
