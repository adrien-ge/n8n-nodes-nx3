/* Customer reference data (BPCUSTOMER). One row per customer. */
SELECT
    BPC.BPCNUM_0 AS CUSTOMER_CODE,
    BPC.BPCNAM_0 AS CUSTOMER_NAME,
    BPC.BCGCOD_0 AS CATEGORY,
    BPC.CUR_0    AS CURRENCY,
    BPC.BPCSTA_0 AS STATUS_CODE,
    ISNULL(ML_STA.LANMES_0, 'Unknown')
        + ' (' + CAST(ISNULL(BPC.BPCSTA_0, 0) AS VARCHAR(10)) + ')' AS STATUS_LABEL,
    BPC.OSTAUZ_0 AS CREDIT_LIMIT
FROM BPCUSTOMER BPC
LEFT JOIN APLSTD ML_STA
       ON  ML_STA.LAN_0    = {{lang}}
       AND ML_STA.LANCHP_0 = 1
       AND ML_STA.LANNUM_0 = BPC.BPCSTA_0
WHERE 1 = 1
/*FILTERS*/
ORDER BY BPC.BPCNUM_0
