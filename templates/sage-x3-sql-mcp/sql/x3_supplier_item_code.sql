/* Item x supplier cross-reference (ITMBPS): the supplier's own item reference, priority and minimum order quantity. */
SELECT
    ITS.BPSNUM_0    AS SUPPLIER_CODE,
    BPS.BPSNAM_0    AS SUPPLIER_NAME,
    ITS.ITMREF_0    AS ITEM,
    ISNULL(NULLIF(DES1.LABEL, ''), ITM.ITMDES1_0) AS X3_DESCRIPTION,
    ITS.ITMREFBPS_0 AS SUPPLIER_ITEM_REF,
    ITS.ITMDESBPS_0 AS SUPPLIER_DESCRIPTION,
    ITS.PIO_0       AS PRIORITY,
    ITS.PURMINQTY_0 AS MINIMUM_PO_QTY,
    ITM.PUU_0       AS PURCHASE_UNIT
FROM ITMBPS ITS
LEFT JOIN BPSUPPLIER BPS ON BPS.BPSNUM_0 = ITS.BPSNUM_0
LEFT JOIN ITMMASTER ITM ON ITM.ITMREF_0 = ITS.ITMREF_0
LEFT JOIN (
    SELECT RTRIM(IDENT1_0) AS ITMREF, MAX(TEXTE_0) AS LABEL
    FROM   ATEXTRA WHERE CODFIC_0 = 'ITMMASTER' AND ZONE_0 = 'DES1AXX' AND LANGUE_0 = {{lang}}
    GROUP  BY RTRIM(IDENT1_0)
) DES1 ON DES1.ITMREF = RTRIM(ITM.ITMREF_0)
WHERE 1 = 1
/*FILTERS*/
ORDER BY ITS.ITMREF_0, ITS.PIO_0, ITS.BPSNUM_0
